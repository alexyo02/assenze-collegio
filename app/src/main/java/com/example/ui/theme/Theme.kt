private val DarkColorScheme = darkColorScheme(
    primary = VioletPrimaryDark,
    onPrimary = VioletOnPrimaryDark,
    primaryContainer = VioletPrimaryContainerDark,
    onPrimaryContainer = VioletOnPrimaryContainerDark,
    secondary = OrchidSecondaryDark,
    onSecondary = OrchidOnSecondaryDark,
    secondaryContainer = OrchidSecondaryContainerDark,
    onSecondaryContainer = OrchidOnSecondaryContainerDark,
    background = VioletBackgroundDark,
    surface = VioletSurfaceDark,
    surfaceVariant = VioletSurfaceVariantDark,
    onSurface = VioletOnSurfaceDark,
    onSurfaceVariant = VioletOnSurfaceVariantDark
)

private val LightColorScheme = lightColorScheme(
    primary = VioletPrimary,
    onPrimary = VioletOnPrimary,
    primaryContainer = VioletPrimaryContainer,
    onPrimaryContainer = VioletOnPrimaryContainer,
    secondary = OrchidSecondary,
    onSecondary = OrchidOnSecondary,
    secondaryContainer = OrchidSecondaryContainer,
    onSecondaryContainer = OrchidOnSecondaryContainer,
    tertiary = RoseTertiary,
    onTertiary = RoseOnTertiary,
    tertiaryContainer = RoseTertiaryContainer,
    onTertiaryContainer = RoseOnTertiaryContainer,
    background = VioletBackgroundLight,
    surface = VioletSurfaceLight,
    surfaceVariant = VioletSurfaceVariantLight,
    onSurface = VioletOnSurfaceLight,
    onSurfaceVariant = VioletOnSurfaceVariantLight
)

val ExpressiveShapes = Shapes(
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(18.dp),
    large = RoundedCornerShape(26.dp),
    extraLarge = RoundedCornerShape(32.dp)
)

@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false, // Keep expressive violet as signature theme
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.background.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = ExpressiveShapes,
        content = content
    )
}
